#!/usr/bin/env python3
"""Generate src/apps/train_stops_data.h from the City of Chicago "CTA - System
Information - List of 'L' Stops" dataset (https://data.cityofchicago.org/d/8pix-ypme).

Usage:
    python3 tools/gen_train_stops.py            # download and regenerate
    python3 tools/gen_train_stops.py stops.json # use a local copy

Output is a compact JSON document embedded in flash, served to the web UI:
    [[routeCode, name, color, [[mapId, stationName, [[stopId, direction], ...]], ...]], ...]
routeCode matches the Train Tracker API's `rt` values.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://data.cityofchicago.org/resource/8pix-ypme.json?$limit=1000"
OUT = Path(__file__).resolve().parent.parent / "src" / "apps" / "train_stops_data.h"

# dataset column -> (Train Tracker route code, display name, color)
LINES = [
    ("red", "Red", "Red Line", "#c60c30"),
    ("blue", "Blue", "Blue Line", "#00a1de"),
    ("brn", "Brn", "Brown Line", "#62361b"),
    ("g", "G", "Green Line", "#009b3a"),
    ("o", "Org", "Orange Line", "#f9461c"),
    ("pnk", "Pink", "Pink Line", "#e27ea6"),
    ("p", "P", "Purple Line", "#522398"),
    ("y", "Y", "Yellow Line", "#f9e300"),
]


def parens(s):
    return re.findall(r"\(([^)]*)\)", s)


def direction_label(stop_name):
    groups = parens(stop_name)
    label = groups[-1] if groups else stop_name
    label = re.sub(r"-Bound$", "-bound", label)
    return label[:1].upper() + label[1:]


def main():
    if len(sys.argv) > 1:
        rows = json.loads(Path(sys.argv[1]).read_text())
    else:
        with urllib.request.urlopen(URL, timeout=60) as r:
            rows = json.load(r)

    lines = []
    for col, code, name, color in LINES:
        stations = {}
        for r in rows:
            if not r.get(col):
                continue
            mid = int(r["map_id"])
            st = stations.setdefault(
                mid, {"name": r["station_name"], "stops": {}, "branch": None}
            )
            groups = parens(r["stop_name"])
            if len(groups) > 1 and "Branch" in groups[0]:
                st["branch"] = groups[0]
            st["stops"][int(r["stop_id"])] = direction_label(r["stop_name"])

        # Disambiguate stations sharing a name on one line (e.g. Blue Line "Western").
        counts = {}
        for st in stations.values():
            counts[st["name"]] = counts.get(st["name"], 0) + 1
        out = []
        for mid, st in stations.items():
            label = st["name"]
            if counts[label] > 1 and st["branch"]:
                label += f" ({st['branch']})"
            dirs = sorted(
                st["stops"].items(), key=lambda kv: ("arrival" in kv[1].lower(), kv[1])
            )
            out.append([mid, label, [[sid, d] for sid, d in dirs]])
        out.sort(key=lambda s: s[1].lower())
        lines.append([code, name, color, out])

    blob = json.dumps(lines, separators=(",", ":"), ensure_ascii=False)
    assert ')json"' not in blob
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by tools/gen_train_stops.py — do not edit by hand.\n"
        "// Source: City of Chicago data portal, dataset 8pix-ypme (CTA 'L' stops).\n"
        "#pragma once\n#include <pgmspace.h>\n\n"
        f'static const char kTrainStopsJson[] PROGMEM = R"json({blob})json";\n',
        encoding="utf-8",
    )
    n = sum(len(l[3]) for l in lines)
    print(f"wrote {OUT} ({len(blob)} bytes, {n} line/station pairs)")


if __name__ == "__main__":
    main()
